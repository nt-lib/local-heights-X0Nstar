/*
This file contains functions for computing the ranks (over Q) of J_0(N) and its factors.

NTLSimpleRank: Attempts to compute the rank of a simple factor of J_0(N)
NTLRankQuo: Attempts to compute the rank of an Atkin-Lehner quotient of J_0(N)
*/

intrinsic NTLSimpleRank(A::ModAbVar) -> RngIntElt, BoolElt
{Attempt to compute the Mordell-Weil rank over `\\QQ` of a simple factor ``A`` of `J_0(N)`.

INPUT:

- ``A`` -- simple modular abelian variety that appears as a factor of `J_0(N)`

OUTPUT: a pair ``rk, tf`` where ``tf`` is a boolean indicating whether ``rk`` is provably
the rank of ``A``. If ``tf`` is ``false`` then ``rk`` is `-1000`.

ALGORITHM:

If `L(A, 1) \\neq 0` the rank is `0`. Otherwise, if the order of vanishing of the
`L`-function of the newform at `s = 1` is `1`, the rank is the degree of its Hecke
eigenvalue field. Otherwise, if ``A`` is an elliptic curve, its rank is computed directly.
}
    tf := true;
    if Dimension(A) eq 0 or IsZeroAt(LSeries(A),1) eq false then
       rk := 0;
    else M := ModularSymbols(Newform(A));
         _,ord_vanishing := LSeriesLeadingCoefficient(M,1,100);
         if ord_vanishing eq 1 then
            rk := Degree(HeckeEigenvalueField(M));
         else if Dimension(A) eq 1 then   // we have an elliptic curve and we try to compute the rank directly
                 E := EllipticCurve(A);
                 rk,ell_tf := Rank(E);
                 assert ell_tf eq true;
              else rk := -1000;
                   tf := false;
              end if;
          end if;
    end if;
    return rk, tf;
end intrinsic;

intrinsic NTLRankQuo(N::RngIntElt, seq_al::SeqEnum) -> RngIntElt, BoolElt
{Attempt to compute the Mordell-Weil rank over `\\QQ` of the quotient `J_0(N)/W`, where
`W` is the group generated by the Atkin-Lehner involutions `w_d` for `d` in ``seq_al``.

INPUT:

- ``N`` -- positive integer
- ``seq_al`` -- sequence of Hall divisors of ``N``; use ``[]`` for the rank of `J_0(N)`
  itself

OUTPUT: a pair ``rk, tf`` where ``tf`` is a boolean indicating whether ``rk`` is provably
the rank of `J_0(N)/W`. If ``tf`` is ``false`` then ``rk`` is `-1000`.

.. SEEALSO::

    :func:`NTLSimpleRank`
}
    J := JZero(N);
    if #seq_al gt 0 then
        J_quo := Image(&*[1+AtkinLehnerOperator(J,i) : i in seq_al]);
    else J_quo := J;
    end if;
    dec := Decomposition(J_quo);
    rk := 0;
    tf := true;

    for A in dec do
        rkA, Atf := NTLSimpleRank(A);
        if Atf eq false then  // cannot compute rank with NTLSimpleRank
           rk := -1000;
           tf := false;
           break;
        else rk := rk + rkA;
        end if;
     end for;

     return rk, tf;
end intrinsic;
