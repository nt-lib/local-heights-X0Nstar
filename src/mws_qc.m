/*
Mordell-Weil sieve for quadratic Chabauty, computing in the class group of the curve over F_p, checks of its
hypotheses, and quadratic Chabauty on X_0(N)^* giving the input of the sieve. Based on mws_qc.m from QCMod
(https://github.com/steffenmueller/QCMod), which goes back to an earlier version of Mordell-Weil sieve by
Michael Stoll.
Not part of the local_heights.spec package; load it after QCMod and src/misc.m.
*/

// scale a sequence of rationals to integers, e.g. projective coordinates before reducing mod p
function clear_denominators(seq)
  d := LCM([Denominator(s) : s in seq]);
  return [d*s : s in seq];
end function;

// G is generated by bas (a pair [P, Q] stands for P - Q) and fake_coeffs are cosets of modulus*G, given by
// coefficient vectors. At each p in sieving_primes not in excluded, let H be the subgroup of J(F_p) generated
// by the d*red_p(b) for b in bas; a coset is kept only if d times its image is congruent to d*(P - base_pt)
// (mod modulus*H) for some P in C(F_p). Asserts that the cosets known_rat_coeffs of the known rational points
// are kept. Returns whether no coset is left, and for each coset whether it is left.
function MWSieve(C, sieving_primes, modulus, bas, base_pt, fake_coeffs : excluded := {Integers()|}, known_rat_coeffs := {}, d := 1)
  bool_list := [true : i in [1..#fake_coeffs]]; // bool_list[i]: coset i is still left
  for p in sieving_primes do
    if IsPrime(p) and p notin excluded then
      Cp := BaseChange(C, Bang(Rationals(), GF(p)));
      G, _, DL := ClassGroup(Cp);
      G := TorsionSubgroup(G); // J(F_p)
      red := func<pt | Place(Cp!ChangeUniverse(clear_denominators(Eltseq(pt)), GF(p)))>;

      // H = d*red_p(G), and the classes d*(P - base_pt) for P in C(F_p) that lie in H
      imbas := [d*DL(red(b[1]) - red(b[2])) : b in bas];
      lcm_orders := LCM([Order(g) : g in imbas]);
      imC := {d*DL(pt - red(base_pt)) : pt in Places(Cp, 1)};
      H := sub<G | imbas>;
      imC := {H | pt : pt in imC | pt in H};
      imbas := ChangeUniverse(imbas, H);

      // pass to H/(modulus*H); since lcm_orders*H = 0, modulus*H = e1*H
      e1 := GCD(modulus, lcm_orders);
      if e1 lt lcm_orders then
        Hq, qmap := quo<H | [e1*g : g in Generators(H)]>;
        imbas := [qmap(b) : b in imbas];
        imC := {qmap(c) : c in imC};
      end if;
      // M is the exponent of H/(modulus*H), so the coefficients only matter mod M
      M := GCD(modulus, Exponent(Parent(imbas[1])));
      assert IsOne(Exponent(Parent(imbas[1])) div M);

      // the cosets of the known rational points are kept
      assert &and[&+[imbas[i]*t[i] : i in [1..#imbas]] in imC : t in known_rat_coeffs];

      // keep a coset only if its image lies in imC
      old_left := #[b : b in bool_list | b];
      for i in [1..#bool_list] do
        if bool_list[i] then
          bool_list[i] := &+[imbas[j]*(fake_coeffs[i][j] mod M) : j in [1..#imbas]] in imC;
        end if;
      end for;
      left := #[b : b in bool_list | b];
      if left lt old_left then printf "  %o cosets eliminated at v = %o\n", old_left - left, p; end if;
      printf "        %o cosets remaining after v=%o\n", left, p;

      if left eq 0 then
        return true, bool_list;
      end if;
    end if;
  end for;
  return false, bool_list;
end function;

// all vectors [a_1, ..., a_g] with 0 <= a_i < N
function all_coeffs(N, g)
    coeffs := [[j] : j in [0..N-1]];
    for i := 1 to g-1 do
        old_coeffs := coeffs;
        coeffs := [];
        for a in old_coeffs do
            for j := 0 to N-1 do
                Append(~coeffs, a cat [j]);
            end for;
        end for;
    end for;
    return coeffs;
end function;

// the vectors mod M*N that are congruent mod M to one in fake_coeffs_mod_M (M and N coprime): the cosets
// mod M*N when there is no information mod N
function combine_fake_good(fake_coeffs_mod_M, M, N)
    as := [];
    rank := #fake_coeffs_mod_M[1];
    as_mod_N := all_coeffs(N, rank);
    for i in [1..#fake_coeffs_mod_M] do
        for j in [1..#as_mod_N] do
            Append(~as, [CRT([fake_coeffs_mod_M[i,l], as_mod_N[j,l]],
                        [M, N]) : l in [1..rank]]);
        end for;
    end for;
    return as;
end function;


// Checks of the hypotheses of MWSieve

// the map Z^#bas -> prod_{p in ps} J(F_p)/M J(F_p) sending the i-th generator to red_p(bas[i])
function reduction_homomorphism(C, bas, M, ps)
  Gamma := FreeAbelianGroup(#bas); // Gamma will be Z^3 for us
  JpMs := [];
  imbases := [* *];
  for p in ps do
    Cp := BaseChange(C, Bang(Rationals(), GF(p)));
    Jp, _, DL := ClassGroup(Cp);
    Jp := TorsionSubgroup(Jp);
    JpM, quot := quo<Jp | M*Jp>;
    red := func<pt | Place(Cp!ChangeUniverse(clear_denominators(Eltseq(pt)), GF(p)))>;
    imbas := [quot(DL(red(b[1]) - red(b[2]))) : b in bas];
    redJM := hom<Gamma -> JpM | imbas>;
    ker := Kernel(redJM);
    printf "p = %o: im = %o, exp(%o) = %o\n", p, AbelianInvariants(Image(redJM)), AbelianInvariants(quo<ker | M*Gamma>), Exponent(quo<ker | M*Gamma>);
    Append(~JpMs, JpM);
    Append(~imbases, imbas);
  end for;
  JpM, inclusions := DirectProduct(JpMs);
  return hom<Gamma -> JpM | [&+[inclusions[j](imbases[j][i]) : j -> p in ps] : i in [1..#bas]]>;
end function;

// d = exponent of the kernel of G/MG -> prod_{p in ps} J(F_p)/M J(F_p), G generated by bas;
// d = 1 shows that [J(Q) : G] is prime to M (J(Q) torsion-free)
function compute_d(C, bas, M, ps)
  redJM := reduction_homomorphism(C, bas, M, ps);
  ker := Kernel(redJM);
  _, quot := quo<Domain(redJM) | M*Domain(redJM)>;
  print AbelianInvariants(quot(ker));
  return Exponent(quot(ker));
end function;

// MWSieve only keeps the F_p-points whose class lies in red_p(G). Since [J(Q) : G] is prime to the primes qs,
// no rational point is lost if [J(F_p) : red_p(G)] has no prime factors outside qs (for X_0(187)^*: qs = [37], so no prime factor outside 37).
// If MWSieve is called with a multiplier d := mult, it compares mult-multiples, and the index to check is
// [mult J(F_p) : mult red_p(G)].
function filter_is_harmless(C, bas, ps, qs : mult := 1)
  ok := true;
  for p in ps do
    Cp := BaseChange(C, Bang(Rationals(), GF(p)));
    Jp, _, DL := ClassGroup(Cp);
    Jp := TorsionSubgroup(Jp);
    red := func<pt | Place(Cp!ChangeUniverse(clear_denominators(Eltseq(pt)), GF(p)))>;
    H := sub<Jp | [mult*DL(red(b[1]) - red(b[2])) : b in bas]>;
    index := #sub<Jp | [mult*g : g in Generators(Jp)]> div #H;
    if mult eq 1 then
      printf "p = %o: [J(F_p) : red(G)] = %o\n", p, Factorization(index);
    else
      printf "p = %o: [m J(F_p) : m red(G)] = %o with m = %o\n", p, Factorization(index), mult;
    end if;
    ok := ok and forall{q : q in PrimeDivisors(index) | q in qs};
  end for;
  return ok;
end function;


// Quadratic Chabauty, giving the input of MWSieve

// quadratic Chabauty at p on the plane model Q(x, y) = 0 of X_0(N)^* (Coleman data to precision N1), then the
// coefficients mod p^N2 of the fake and the known rational points in the basis divisors; retries with larger
// N1 on errors. Returns these coefficients, the known points and the bad Q_p-points.
function run_QC(Q, N, p, N1, N2, divisors, base_pt, splitting_indices)
  assert N1 ge N2;

  try
    printf "Computing Coleman data with N1 = %o.\n", N1;
    data := coleman_data(Q, p, N1 : useU := false);

    printf "\nStarting quadratic Chabauty for p = %o.\n", p;
    polys := NTLStarQuotientCleanCorrespondences(N, [p])[1];
    printf "Polynomials in T_p passed to QCModAffine (use_polys): %o\n", polys;
    printf "Clean correspondences of trace 0, as polynomials in T_p: %o\n",
        NTLStarQuotientCleanCorrespondences(N, [p] : trace_zero := true)[1];
    time good_affine_rat_pts_xy, no_fake_pts, bad_affine_rat_pts_xy, data, fake_rat_pts, bad_Qppoints := QCModAffine(Q, p : use_polys := polys,
        number_of_correspondences := #polys-1, printlevel:=1, N := N1, prec := 40, base_point := base_pt);
    printf "There are %o fake rational points.\n", #fake_rat_pts;
    printf "There are %o bad Q_%o-points.\n", #bad_Qppoints, p;

    // coefficients of the solutions in the basis divisors, from Coleman data to precision N2;
    // retries with larger N2 (up to N1) on errors
    function recompute_Coleman_data(N1, N2, fake_rat_pts)
      try
        fake_rat_pts_new := [];
        for i in [1..#fake_rat_pts] do
          fake_rat_pts_new[i] := [ChangePrecision(fake_rat_pts[i,j], N2) : j in [1..2]];
        end for;
        printf "Re-computing Coleman data with N2 = %o.\n", N2;
        data := coleman_data(Q, p, N2 : useU := false);
        fake_coeffs_mod_pN, rat_coeffs_mod_pN := coefficients_mod_pN(fake_rat_pts_new, good_affine_rat_pts_xy, divisors, base_pt, splitting_indices, data);
      catch e
        printf "%o\n", e;
        if N2 lt N1 then
          N2 +:= 1;
        else
          error "reached N2 = N1";
        end if;
        printf "trying N1 = %o, N2 = %o ...\n", N1, N2;
        return $$(N1, N2, fake_rat_pts);
      end try;
      return fake_coeffs_mod_pN, rat_coeffs_mod_pN;
    end function;

    fake_coeffs_mod_pN, rat_coeffs_mod_pN := recompute_Coleman_data(N1, N2, fake_rat_pts);
  catch e
    N1 +:= 1;
    return $$(Q, N, p, N1, N2, divisors, base_pt, splitting_indices);
  end try;

  return fake_coeffs_mod_pN, rat_coeffs_mod_pN, good_affine_rat_pts_xy, bad_Qppoints;
end function;

// whether QC finds exactly the known points, with coordinates congruent mod M to those in known_coords
// (a sequence of pairs <affine point, coordinates>); this shows that QC uses the same basis as the sieve
function check_known_coords(rat_pts_xy, rat_coeffs_mod_pN, known_coords, M)
  if {P : P in rat_pts_xy} ne {t[1] : t in known_coords} then
    return false;
  end if;
  for i in [1..#rat_pts_xy] do
    coords := [t[2] : t in known_coords | t[1] eq rat_pts_xy[i]][1];
    if not forall{j : j in [1..#coords] | IsDivisibleBy(rat_coeffs_mod_pN[i,j] - coords[j], M)} then
      return false;
    end if;
  end for;
  return true;
end function;
